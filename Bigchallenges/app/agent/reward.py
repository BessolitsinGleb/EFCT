"""Функция награды агента — ПИШЕТ АВТОР.

Как это устроено:
  1. Агент выбирает ячейку (одну из 8 лучших по формуле).
  2. Симулятор «проматывает» время до следующего решения: приходят и уезжают контейнеры,
     при выдаче мешающие контейнеры переставляются, всё оплачивается по тарифу (раздел 4.7).
  3. Всё, что случилось за этот промежуток, собрано в StepEvents и передаётся в reward().
  4. reward() возвращает одно число: чем больше, тем лучше. PPO учится максимизировать
     сумму наград с дисконтом gamma = 0.995 (последствия решения проявляются через дни).

Удобная единица — «перестановки»: -1.0 = одна лишняя перестановка.
Типичные значения полей за один шаг (из симулятора, поток 0.6 конт./ч):
  rehandles   — обычно 0, иногда 1–3 (когда при выдаче контейнер оказался заставлен);
  move_cost   — 150–500 у. е. (размещение ~150–300, перестановка ~100–400, выдача ~150–300);
  rejected    — редко True, в основном при загрузке площадки > 75 %.

Проверить свою функцию: python rl/check_reward.py — покажет её значения на реальных событиях симулятора.
Сигнатуру и поля не меняй: на них опирается среда rl/env.py.
"""
from dataclasses import dataclass


@dataclass
class StepEvents:
    placed: bool            # новый контейнер поставлен (False — шаг перестановки или отказ)
    rejected: bool          # для нового контейнера не нашлось ни одной допустимой ячейки
    rehandles: int          # перестановок мешающих контейнеров при выдачах за этот промежуток
    move_cost: float        # стоимость всех операций за промежуток, у. е.
    premarshal_moves: int   # заблаговременные перестановки (P1), пока всегда 0
    relocation: bool        # True — решение было о том, куда переставить мешающий контейнер


@dataclass
class RewardConfig:
    """Коэффициенты автора, приведённые к «цене» каждого события.
    Было: placed 0.75·10, rejected 0.25·10, rear 1.5, reloc 1.5, деньги ·0.01·0.2."""
    rehandle: float = 3.4       # одна лишняя перестановка: 1.5 (rear) + 1.5 (шаг перестановки) + 0.4 (доплата)
    reject: float = 10.0        # отказ в приёме: 7.5 + 2.5 — разница «поставили / не поставили»
    money: float = 0.002        # за 1 у. е. стоимости операций (200 у. е. = 0.4)
    premarshal: float = 0.5     # заблаговременная перестановка: небольшой штраф сверх её стоимости,
                                # чтобы агент не переставлял ради переставлений (польза — меньше rehandles)


def reward(ev: StepEvents, cfg: RewardConfig = RewardConfig()) -> float:
    """Минимизируем деньги и особенно лишние перестановки; отказ — штраф, но не главный."""
    return -(cfg.rehandle * ev.rehandles
             + cfg.reject * ev.rejected
             + cfg.money * ev.move_cost
             + cfg.premarshal * ev.premarshal_moves)
